"""A fake `orca-slicer` for print-fab tests (CI has no slicer)."""

from pathlib import Path

# Writes 300 layers of 0.2 mm, using T1 (body) and T0 (interface) on the first 10 layers.
FAKE_SLICER = r"""#!/bin/sh
out=""
prev=""
for a in "$@"; do
  [ "$prev" = "--outputdir" ] && out="$a"
  prev="$a"
done
g="$out/plate_1.gcode"
{
  echo "; HEADER_BLOCK_START"
  echo "; generated by OrcaSlicer 2.5.1 on 2026-11-19 at 00:00:00"
  echo "; total layer number: 300"
  echo "; HEADER_BLOCK_END"
  echo ""
  echo "; EXECUTABLE_BLOCK_START"
  echo "PRINT_START"
  echo "T1"
  i=1
  while [ $i -le 300 ]; do
    echo ";LAYER_CHANGE"
    echo ";Z:$((i / 5)).$(( (i % 5) * 2 ))"
    echo ";HEIGHT:0.2"
    if [ $i -le 10 ]; then echo "T0"; echo "G1 X1 E.1"; echo "T1"; fi
    echo "G1 X2 Y2 E.5"
    i=$((i + 1))
  done
  echo "PRINT_END"
  echo "; EXECUTABLE_BLOCK_END"
  echo "; filament used [mm] = 100.0, 900.0, 0.00, 0.00"
  echo "; filament used [g] = 0.30, 2.70, 0.00, 0.00"
  echo "; total filament used [g] = 3.00"
  echo "; estimated printing time (normal mode) = 12m 30s"
  echo "; CONFIG_BLOCK_START"
  echo "; enable_prime_tower = 1"
  echo "; CONFIG_BLOCK_END"
} > "$g"
echo "args: $*"
echo '{"return_code": 0, "error_string": "Success."}' > "$out/result.json"
"""


def install_fake_slicer(folder: Path, monkeypatch) -> Path:
    """Write the fake and point `LUREGEN_SLICER` at it (host runtime)."""
    fake = folder / "fake-orca"
    fake.write_text(FAKE_SLICER)
    fake.chmod(0o755)
    monkeypatch.setenv("LUREGEN_SLICER", str(fake))
    monkeypatch.setenv("LUREGEN_SLICER_RUNTIME", "host")
    return fake
