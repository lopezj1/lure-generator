def test_extrusion_state_and_markers():
    tp = extract_print(SYNTH)
    kinds = tp.seg_kind.tolist()
    # X10 E1 extrudes; X20 E1 (absolute, no delta) travels; after G92 E0, E0.5 extrudes.
    assert kinds[:3] == [EXTRUDE, TRAVEL, EXTRUDE]
    assert tp.width[0] == 450 and tp.height[0] == 200 and tp.width[1] == 0
    assert tp.points[3].tolist() == [20, 10, pytest.approx(0.2)]
    assert tp.points[4].tolist() == [20, 10, pytest.approx(1.2)]  # G91 Z hop
    assert kinds[3] == TRAVEL and kinds[4] == EXTRUDE and kinds[5] == TRAVEL  # M83, retract
    assert tp.feed[4] == 1200
    markers = tp.meta["markers"]
    assert [m["type"] for m in markers] == ["pause"]  # first T sets the tool; M104 T1 doesn't
    assert markers[0]["command"] == "M600" and markers[0]["layer"] == 1
    assert tp.tool[4] == 1 and tp.tool[0] == 0
    arc = np.flatnonzero(tp.line == SYNTH.splitlines().index("G3 X0 Y0 I1 J0 Z1.5 F3000") + 1)
    assert len(arc) > 8  # a full helix turn, tessellated
    radii = np.hypot(tp.points[arc + 1, 0] - 1, tp.points[arc + 1, 1])
    assert np.allclose(radii, 1, atol=1e-5)
    assert tp.points[arc[-1] + 1].tolist() == pytest.approx([0, 0, 1.5])
    # G92 X100 relocates the head: the next move starts with a jump.
    assert kinds[-2:] == [JUMP, TRAVEL]
    assert tp.points[-1, 0] == 110


