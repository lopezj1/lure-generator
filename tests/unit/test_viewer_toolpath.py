def test_multimaterial_layers_features_and_tool_changes():
    tp = extract_print(MULTI.read_text())
    meta = tp.meta
    assert meta["layer_count"] == meta["source"]["header_layers"] == _layer_changes(MULTI) == 2
    assert [ly["z"] for ly in meta["layers"][1:]] == [5.25, 5.45]
    assert meta["layers"][1]["height"] == 0.2
