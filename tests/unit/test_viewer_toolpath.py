def _assert_same(a, b):
    assert a.kind == b.kind
    for attr in ("points", "seg_kind", "tool", "feed", "line", "feature", "layer", "width", "time"):
        x, y = getattr(a, attr), getattr(b, attr)
        assert (x is None) == (y is None)
        if x is not None:
            assert x.dtype == y.dtype and np.array_equal(x, y)


@pytest.mark.parametrize("path", [MULTI, CUBE, ROUGH, GOLDEN[0]], ids=lambda p: p.name)
def test_round_trip(path: Path):
    tp = extract(path.read_text())
    data = encode(tp)
    assert data[:4] == MAGIC
    header = read_header(data)
    assert header["version"] == 1 and header["segments"] == tp.n_segments
    data_start = 12 + int.from_bytes(data[8:12], "little")
    assert data_start % 8 == 0
    names = [a["name"] for a in header["arrays"]]
    expected = ["points", "kind", "tool", "feed", "line"]
    if tp.kind == "print":
        expected += ["feature", "layer", "width", "height"]
    else:
        expected += ["time"]
    assert names == expected
    for entry in header["arrays"]:
        assert entry["offset"] % 8 == 0 and entry["offset"] >= data_start
    back = decode(data)
    _assert_same(tp, back)
    assert back.meta == {
        k: v for k, v in header.items() if k not in ("format", "version", "kind", "arrays")
    }
    assert encode(back) == data
    assert back.points.dtype == np.float32 and back.points.shape == (tp.n_segments + 1, 3)


