    assert meta["tools"][2]["color"] == "#FFFFFF"
    # The prime tower is printed by both tools.
    tower = meta["features"].index("Prime tower")
    assert set(np.unique(tp.tool[(tp.feature == tower) & (tp.seg_kind == EXTRUDE)])) == {1, 2}


