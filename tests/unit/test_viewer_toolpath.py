SAMPLES = os.environ.get("LUREGEN_TOOLPATH_SAMPLES")


@pytest.mark.integration
@pytest.mark.skipif(not SAMPLES, reason="set LUREGEN_TOOLPATH_SAMPLES to a folder of samples")
def test_large_samples_perf(tmp_path: Path):
    files = [p for p in sorted(Path(SAMPLES).iterdir()) if p.suffix in (".gcode", ".txt", ".nc")]
    assert files
    for path in files:
        t0 = time.perf_counter()
        out = encode_file(path, out=tmp_path / f"{path.name}.bin", force=True)
        elapsed = time.perf_counter() - t0
        data = out.read_bytes()
        packed = len(gzip.compress(data, 6))
        header = read_header(data)
        print(f"{path.name}: {elapsed:.2f} s, {len(data) / 1e6:.2f} MB, gzip {packed / 1e6:.2f} MB")
        assert elapsed < 10 and packed < 10e6
        if header["kind"] == "print" and "header_layers" in header["source"]:
            assert header["layer_count"] == header["source"]["header_layers"]
            changes = [m for m in header["markers"] if m["type"] == "tool_change"]
            assert len(changes) == header["source"].get("tool_changes", len(changes))
