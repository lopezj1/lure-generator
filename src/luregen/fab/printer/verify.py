"""Parse OrcaSlicer G-code and diff it against reference prints (#34).

Reads the stats comments (time, filament), counts layers, lists embedded thumbnails, parses
the `; CONFIG_BLOCK` key/values and extracts the start and end sections with the Klipper
macros they call. `diff_gcode` compares two parsed files; `verify_against_references` runs it
for every `reference/*.gcode` of a printer, and reports cleanly when there are none yet.
"""

import re
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

from luregen.fab.printer.gcode_post import LAYER_CHANGE

_GENERATED_RE = re.compile(r"^; generated by (.+?) ([\d.]+\S*)(?: on (.+))?$")
_STAT_RE = re.compile(r"^; (filament used \[(mm|g|cm3)\]|total filament used \[g\]) = (.+)$")
_STAT_FIELD = {"mm": "filament_mm", "g": "filament_g", "cm3": "filament_cm3"}
_TIME_RE = re.compile(r"^; estimated printing time \(normal mode\) = (.+)$")
_TOTAL_LAYERS_RE = re.compile(r"^; (?:total layer number:|total layers count =) (\d+)")
_THUMB_RE = re.compile(r"^; (?:thumbnail|thumbnail_(\w+)) begin (\d+)x(\d+) (\d+)")
_CONFIG_RE = re.compile(r"^; ([A-Za-z0-9_]+) = ?(.*)$")
_MACRO_RE = re.compile(r"^([A-Z][A-Z0-9_]*[A-Z0-9])(?:\s|$)")
_GCODE_WORD_RE = re.compile(r"^[GMT]\d")
_TOOL_RE = re.compile(r"^T(\d+)\s*(?:;|$)")
_EXTRUDE_RE = re.compile(r"^G[123]\b[^;]*\bE\.?\d")  # positive E: printing, not retracting
# Per-object bookkeeping, not start/end macros.
_SKIP_MACROS = ("EXCLUDE_OBJECT",)

# Config keys that differ between any two slices of the same settings.
VOLATILE_KEYS = frozenset(
    {"different_settings_to_system", "print_settings_id", "printer_settings_id"}
)


@dataclass(frozen=True)
class Thumbnail:
    width: int
    height: int
    format: str  # PNG unless the block names another
    size: int  # base64 length declared in the header


@dataclass
class GcodeSummary:
    path: str
    generator: str | None = None
    generator_version: str | None = None
    estimated_time_s: int | None = None
    filament_mm: float | None = None
    filament_g: float | None = None
    filament_cm3: float | None = None
    # Per filament slot (T0, T1, …), from the comma-separated stats.
    filament_g_by_slot: list[float] = field(default_factory=list)
    filament_mm_by_slot: list[float] = field(default_factory=list)
    # Tool changes after the start G-code (switches to a different T<n>).
    tool_changes: int = 0
    tools_used: list[int] = field(default_factory=list)
    layer_count: int = 0
    header_layer_count: int | None = None
    max_z: float | None = None
    thumbnails: list[Thumbnail] = field(default_factory=list)
    config: dict[str, str] = field(default_factory=dict)
    start_gcode: list[str] = field(default_factory=list)
    end_gcode: list[str] = field(default_factory=list)

    @property
    def start_macros(self) -> list[str]:
        return macros(self.start_gcode)

    @property
    def end_macros(self) -> list[str]:
        return macros(self.end_gcode)

    def to_dict(self, with_config: bool = False) -> dict[str, Any]:
        out = asdict(self)
        out["thumbnails"] = [f"{t.width}x{t.height}/{t.format}" for t in self.thumbnails]
        out["start_macros"] = self.start_macros
        out["end_macros"] = self.end_macros
        for key in ("start_gcode", "end_gcode"):
            out.pop(key)
        if not with_config:
            out["config"] = len(self.config)
        return out


def parse_duration(text: str) -> int:
    """'1d 2h 17m 35s' → seconds."""
    units = {"d": 86400, "h": 3600, "m": 60, "s": 1}
    parts = re.findall(r"(\d+)\s*([dhms])", text)
    if not parts:
        raise ValueError(f"unrecognised duration {text!r}")
    return sum(int(n) * units[u] for n, u in parts)


def macros(lines: list[str]) -> list[str]:
    """Klipper macro names called in `lines`, in order (G/M/T words and comments skipped)."""
    out = []
    for line in lines:
        code = line.split(";", 1)[0].strip()
        if not code or _GCODE_WORD_RE.match(code):
            continue
        if (m := _MACRO_RE.match(code)) and not m.group(1).startswith(_SKIP_MACROS):
            out.append(m.group(1))
    return out


def _executable_lines(lines: list[str]) -> list[str]:
    start = end = None
    for i, line in enumerate(lines):
        if line.startswith("; EXECUTABLE_BLOCK_START"):
            start = i + 1
        elif line.startswith("; EXECUTABLE_BLOCK_END"):
            end = i
    return lines[start or 0 : end if end is not None else len(lines)]


def _split_start_end(body: list[str]) -> tuple[list[str], list[str]]:
    """Start = before the first layer change; end = after the last extruding move."""
    first = next((i for i, line in enumerate(body) if line.strip() == LAYER_CHANGE), None)
    if first is None:
        return body, []
    last = max(
        (i for i in range(first, len(body)) if _EXTRUDE_RE.match(body[i])), default=len(body) - 1
    )
    return body[:first], body[last + 1 :]


def parse_gcode(path: Path) -> GcodeSummary:
    text = Path(path).read_text(errors="replace")
    lines = text.splitlines()
    summary = GcodeSummary(path=str(path))

    in_config = False
    for line in lines:
        if line.startswith("; CONFIG_BLOCK_START"):
            in_config = True
            continue
        if line.startswith("; CONFIG_BLOCK_END"):
            in_config = False
            continue
        if in_config:
            if m := _CONFIG_RE.match(line):
                summary.config[m.group(1)] = m.group(2)
            continue
        if not line.startswith(";"):
            continue
        if line.strip() == LAYER_CHANGE:
            summary.layer_count += 1
        elif m := _GENERATED_RE.match(line):
            summary.generator, summary.generator_version = m.group(1), m.group(2)
        elif m := _STAT_RE.match(line):
            # One value per filament slot, comma-separated.
            values = [float(v) for v in m.group(3).split(",") if v.strip()]
            field_name = _STAT_FIELD[m.group(2) or "g"]
            setattr(summary, field_name, round(sum(values), 4))
            if m.group(2) and field_name in ("filament_g", "filament_mm"):
                setattr(summary, f"{field_name}_by_slot", [round(v, 4) for v in values])
        elif m := _TIME_RE.match(line):
            summary.estimated_time_s = parse_duration(m.group(1))
        elif m := _TOTAL_LAYERS_RE.match(line):
            summary.header_layer_count = int(m.group(1))
        elif line.startswith("; max_z_height:"):
            summary.max_z = float(line.split(":", 1)[1])
        elif m := _THUMB_RE.match(line):
            fmt = (m.group(1) or "PNG").upper()
            summary.thumbnails.append(
                Thumbnail(int(m.group(2)), int(m.group(3)), fmt, int(m.group(4)))
            )

    body = _executable_lines(lines)
    summary.start_gcode, summary.end_gcode = _split_start_end(body)
    summary.tool_changes, summary.tools_used = count_tool_changes(body)
    return summary


def count_tool_changes(body: list[str]) -> tuple[int, list[int]]:
    """(changes, tools) from `T<n>` lines: the first selection is the start tool, every later
    switch to a different tool is a change. Tools are listed in order of first use."""
    current: int | None = None
    changes = 0
    tools: list[int] = []
    for line in body:
        if not line.startswith("T") or not (m := _TOOL_RE.match(line)):
            continue
        tool = int(m.group(1))
        if tool not in tools:
            tools.append(tool)
        if current is not None and tool != current:
            changes += 1
        current = tool
    return changes, tools


@dataclass
class GcodeDiff:
    ours: str
    reference: str
    changed: dict[str, tuple[str, str]] = field(default_factory=dict)  # key: (ours, ref)
    only_ours: list[str] = field(default_factory=list)
    only_reference: list[str] = field(default_factory=list)
    start_macros: tuple[list[str], list[str]] | None = None  # set only when they differ
    end_macros: tuple[list[str], list[str]] | None = None
    thumbnails: tuple[list[str], list[str]] | None = None

    @property
    def clean(self) -> bool:
        return not (
            self.changed
            or self.only_ours
            or self.only_reference
            or self.start_macros
            or self.end_macros
            or self.thumbnails
        )

    def to_dict(self) -> dict[str, Any]:
        return {**asdict(self), "clean": self.clean}


def diff_gcode(
    ours: GcodeSummary, ref: GcodeSummary, ignore: frozenset[str] = VOLATILE_KEYS
) -> GcodeDiff:
    diff = GcodeDiff(ours=ours.path, reference=ref.path)
    a = {k: v for k, v in ours.config.items() if k not in ignore}
    b = {k: v for k, v in ref.config.items() if k not in ignore}
    diff.changed = {k: (a[k], b[k]) for k in sorted(a.keys() & b.keys()) if a[k] != b[k]}
    diff.only_ours = sorted(a.keys() - b.keys())
    diff.only_reference = sorted(b.keys() - a.keys())
    if ours.start_macros != ref.start_macros:
        diff.start_macros = (ours.start_macros, ref.start_macros)
    if ours.end_macros != ref.end_macros:
        diff.end_macros = (ours.end_macros, ref.end_macros)
    thumbs = [sorted(f"{t.width}x{t.height}/{t.format}" for t in s.thumbnails) for s in (ours, ref)]
    if thumbs[0] != thumbs[1]:
        diff.thumbnails = (thumbs[0], thumbs[1])
    return diff


def reference_files(printer_root: Path) -> list[Path]:
    return sorted((Path(printer_root) / "reference").glob("*.gcode"))


@dataclass
class VerifyReport:
    summary: GcodeSummary
    diffs: list[GcodeDiff]
    note: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "summary": self.summary.to_dict(),
            "diffs": [d.to_dict() for d in self.diffs],
            "note": self.note,
        }


def verify_against_references(gcode: Path, printer_root: Path) -> VerifyReport:
    """Parse `gcode` and diff it against each reference file; a note explains when none exist."""
    summary = parse_gcode(gcode)
    refs = reference_files(printer_root)
    if not refs:
        note = f"no reference G-code in {Path(printer_root) / 'reference'}; config diff skipped"
        return VerifyReport(summary, [], note)
    return VerifyReport(summary, [diff_gcode(summary, parse_gcode(r)) for r in refs])
